import { Type, type Schema } from '@google/genai';
import { LEVEL_COUNT } from '../../../src/common/levels';
import { parseEnrichOptions, type EnrichOptions } from './enrich-options';

/** Matches the `Word.aiFlag` column size. */
export const MAX_FLAG_LENGTH = 300;
const LEVEL_TO_CEFR = ['', 'A1', 'A2', 'B1', 'B2', 'C1', 'C2'];

export interface CheckOptions extends EnrichOptions {
  /** Only words of this level. */
  level?: number;
  /** Also re-check words the AI has already checked. */
  recheck: boolean;
}

/** The word content shown to the checker, as stored in the database. */
export interface CheckEntry {
  word: string;
  pos: string[];
  level: number;
  ipa: string | null;
  meaningVi: string | null;
  meaningEn: string | null;
  exampleEn: string | null;
  exampleVi: string | null;
}

export const CHECK_RESPONSE_SCHEMA: Schema = {
  type: Type.ARRAY,
  items: {
    type: Type.OBJECT,
    properties: {
      k: { type: Type.STRING },
      ok: { type: Type.BOOLEAN },
      issue: { type: Type.STRING },
    },
    required: ['k', 'ok'],
  },
};

/** `--level 2 --recheck` plus the shared `--limit/--batch/--delay` flags. */
export function parseCheckOptions(argv: string[]): CheckOptions {
  const options: CheckOptions = {
    ...parseEnrichOptions(argv),
    recheck: argv.includes('--recheck'),
  };
  const i = argv.indexOf('--level');
  if (i >= 0) {
    const level = Number(argv[i + 1]);
    if (!Number.isInteger(level) || level < 1 || level > LEVEL_COUNT) {
      throw new Error(`--level phải là số nguyên từ 1 đến ${LEVEL_COUNT}`);
    }
    options.level = level;
  }
  return options;
}

/** Entries are numbered ("k") rather than identified by word, since the same
 * word can appear at two levels. */
export function buildCheckPrompt(entries: CheckEntry[]): string {
  const list = entries
    .map((e, i) =>
      JSON.stringify({
        k: String(i + 1),
        word: e.word,
        pos: e.pos.join('/').toLowerCase(),
        cefr: LEVEL_TO_CEFR[e.level],
        ipa: e.ipa,
        meaningVi: e.meaningVi,
        meaningEn: e.meaningEn,
        exampleEn: e.exampleEn,
        exampleVi: e.exampleVi,
      }),
    )
    .join('\n');
  return `You are proofreading an English vocabulary course for Vietnamese learners.
The entries below were generated by an AI and may contain mistakes. For EACH entry check:
- meaningVi: a correct, common Vietnamese meaning for this part of speech
- ipa: plausible General American IPA for the word
- meaningEn: a correct English definition
- exampleEn: uses the word naturally and correctly; exampleVi translates it correctly
Small wording or style differences are fine — only flag real errors a learner would be misled by.
Return one object per entry, in the same order: {"k": same k, "ok": true} when everything is
acceptable, or {"k": same k, "ok": false, "issue": "..."} where issue is a short Vietnamese
explanation (max 25 words) naming the wrong field and, if you can, the correct value.
Entries (one JSON object per line):
${list}`;
}

/** Index of each answered entry → null (looks fine) or the issue text.
 * Malformed, unknown or duplicate answers are left out, so those entries stay
 * unchecked and are retried next run. */
export function parseCheckResults(
  items: unknown[],
  count: number,
): Map<number, string | null> {
  const results = new Map<number, string | null>();
  for (const item of items) {
    if (!item || typeof item !== 'object') continue;
    const { k, ok, issue } = item as Record<string, unknown>;
    const index = Number(k) - 1;
    if (!Number.isInteger(index) || index < 0 || index >= count) continue;
    if (results.has(index) || typeof ok !== 'boolean') continue;
    if (ok) {
      results.set(index, null);
      continue;
    }
    const text = typeof issue === 'string' ? issue.trim() : '';
    if (text) results.set(index, text.slice(0, MAX_FLAG_LENGTH));
  }
  return results;
}
